"""Generate Python source for priced GMC variants and their dispatcher."""

from pathlib import Path

from gmc.cost import PricedVariant, price_source
from gmc.lower import Step
from gmc.parser import parse


class CodegenError(Exception):
    """A source operand or variant cannot be emitted safely."""


MULTIPLY_KERNELS = frozenset(
    {"GEMM", "SYMM", "TRMM", "SYSYMM", "TRSYMM", "TRTRMM"}
)
SOLVE_KERNELS = frozenset(
    {
        "TRSM",
        "TRSYSV",
        "TRTRSV",
        "GEGESV",
        "GESYSV",
        "GETRSV",
        "SYGESV",
        "SYSYSV",
        "SYTRSV",
        "POGESV",
        "POSYSV",
        "POTRSV",
    }
)
RUNTIME_IMPORTS = (
    "GEMM",
    "SYMM",
    "TRMM",
    "SYSYMM",
    "TRSYMM",
    "TRTRMM",
    "TRSM",
    "TRSYSV",
    "TRTRSV",
    "GEGESV",
    "GESYSV",
    "GETRSV",
    "SYGESV",
    "SYSYSV",
    "SYTRSV",
    "POGESV",
    "POSYSV",
    "POTRSV",
    "transpose",
)


def _parse_operand_source(source: str) -> tuple[str, list[str]]:
    text = source.strip()
    operators: list[str] = []
    while True:
        operator = next(
            (candidate for candidate in ("trans", "inv")
             if text.startswith(f"{candidate}( ") or text.startswith(f"{candidate}(")),
            None,
        )
        if operator is None:
            break
        prefix = f"{operator}("
        if not text.startswith(prefix) or not _has_outer_parentheses(text[len(operator):]):
            raise CodegenError(f"invalid operand source {source!r}")
        operators.append(operator)
        text = text[len(prefix) : -1].strip()

    if not text.isidentifier():
        raise CodegenError(f"invalid operand source {source!r}")
    return text, operators


def _has_outer_parentheses(text: str) -> bool:
    if not text.startswith("(") or not text.endswith(")"):
        return False
    depth = 0
    for index, character in enumerate(text):
        if character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
            if depth == 0 and index != len(text) - 1:
                return False
        if depth < 0:
            return False
    return depth == 0


def _is_temporary(name: str) -> bool:
    return name.startswith("T") and name[1:].isdigit()


def base_matrix_name(source: str) -> str | None:
    name, _ = _parse_operand_source(source)
    return None if _is_temporary(name) else name


def emit_operand(source: str) -> str:
    name, operators = _parse_operand_source(source)
    expression = name if _is_temporary(name) else f'mats["{name}"]'
    transpose_count = operators.count("trans")
    if transpose_count % 2:
        return f"transpose({expression})"
    return expression


def emit_call(step: Step) -> str:
    left = emit_operand(step.left.source)
    right = emit_operand(step.right.source)
    if step.kernel in MULTIPLY_KERNELS:
        return f"{step.dest} = {step.kernel}({left}, {right})"
    if step.kernel not in SOLVE_KERNELS:
        raise CodegenError(f"unknown kernel {step.kernel!r}")
    inverted_left = "True" if step.left.inverted else "False"
    return (
        f"{step.dest} = {step.kernel}({left}, {right}, "
        f"inverted_left={inverted_left})"
    )


def generate_module(priced: list[PricedVariant], declarations: list[str]) -> str:
    if not priced:
        raise CodegenError("cannot generate a module without variants")

    function_names = [variant.lowered.h_label for variant in priced]
    if len(set(function_names)) != len(function_names):
        raise CodegenError("variant labels must be unique")

    q_count = len(priced[0].lowered.steps) + 2
    q_names = [f"q{index}" for index in range(q_count)]
    lines = [
        "# Generated by gmc-edu. Do not edit.",
        "from gmc.runtime import (",
        *(f"    {name}," for name in RUNTIME_IMPORTS),
        ")",
        "",
    ]

    for variant in priced:
        label = variant.lowered.h_label
        lines.extend(
            [
                f"def cost_{label}(q):",
                f"    {', '.join(q_names)} = q",
                f"    return {variant.symbolic_sum}",
                "",
                f"def variant_{label}(mats):",
            ]
        )
        lines.extend(f"    {emit_call(step)}" for step in _steps(variant))
        result = (
            variant.lowered.steps[-1].dest
            if variant.lowered.steps
            else emit_operand(variant.lowered.result.source)
        )
        lines.extend([f"    return {result}", ""])

    lines.extend(
        [
            f"VARIANTS = [{', '.join(f'variant_{label}' for label in function_names)}]",
            f"COSTERS = [{', '.join(f'cost_{label}' for label in function_names)}]",
            f"LABELS = [{', '.join(f'\"{label}\"' for label in function_names)}]",
            "",
            "def dispatch(mats, q):",
            "    costs = [cost(q) for cost in COSTERS]",
            "    index = min(range(len(costs)), key=lambda item: costs[item])",
            "    return VARIANTS[index](mats)",
        ]
    )
    return "\n".join(lines) + "\n"


def _steps(variant: PricedVariant) -> list[Step]:
    return [priced_step.step for priced_step in variant.priced_steps]


def generate_source(source: str) -> str:
    priced = price_source(source)
    declarations = [declaration.name for declaration in parse(source).declarations]
    return generate_module(priced, declarations)


def generate_file(input_path: str, output_path: str) -> None:
    source = Path(input_path).read_text(encoding="utf-8")
    generated = generate_source(source)
    with Path(output_path).open("w", encoding="utf-8", newline="\n") as output:
        output.write(generated.rstrip("\n") + "\n")