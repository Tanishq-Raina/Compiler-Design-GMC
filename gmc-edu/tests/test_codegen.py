import ast
from pathlib import Path
import subprocess
import sys

from gmc.codegen import base_matrix_name, emit_operand, generate_file, generate_source


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def _source(filename: str) -> str:
    return (PROJECT_ROOT / "examples" / filename).read_text(encoding="utf-8")


def _cost_namespace(source: str) -> dict:
    module = ast.parse(source)
    cost_functions = [
        node
        for node in module.body
        if isinstance(node, ast.FunctionDef) and node.name.startswith("cost_")
    ]
    cost_module = ast.Module(body=cost_functions, type_ignores=[])
    namespace: dict = {}
    exec(compile(cost_module, "<generated-cost-functions>", "exec"), namespace)
    return namespace


def test_emit_operand_transforms_and_temporary_names() -> None:
    assert emit_operand("T1") == "T1"
    assert emit_operand("A") == 'mats["A"]'
    assert emit_operand("inv(L)") == 'mats["L"]'
    assert emit_operand("trans(B)") == 'transpose(mats["B"])'
    assert emit_operand("inv(trans(A))") == 'transpose(mats["A"])'
    assert emit_operand("trans(inv(A))") == 'transpose(mats["A"])'
    assert emit_operand("trans(trans(A))") == 'mats["A"]'
    assert base_matrix_name("T2") is None
    assert base_matrix_name("inv(trans(A))") == "A"


def test_simple_module_is_valid_python_and_has_expected_functions() -> None:
    generated = generate_source(_source("simple.gmc"))
    ast.parse(generated)
    assert "def variant_E0" in generated
    assert "def variant_E1" in generated
    assert "def cost_E0" in generated
    assert "def cost_E1" in generated
    assert "def dispatch" in generated
    assert "return q0*q2*q2+2*q0*q2*q3" in generated
    assert "return q1*q1*q3+2*q0*q1*q3" in generated
    assert 'TRSM(mats["A"], mats["L"], inverted_left=False)' in generated
    assert 'TRSM(mats["L"], transpose(mats["B"]), inverted_left=True)' in generated
    assert 'transpose(mats["B"])' in generated
    assert "inv(" not in generated


def test_generated_simple_cost_functions_match_runtime_costs() -> None:
    generated = generate_source(_source("simple.gmc"))
    costs = _cost_namespace(generated)
    sizes = [10, 8, 8, 5]
    assert costs["cost_E0"](sizes) == 1440
    assert costs["cost_E1"](sizes) == 1120
    assert min(costs["cost_E0"](sizes), costs["cost_E1"](sizes)) == 1120


def test_four_factor_module_has_five_variants_and_costers() -> None:
    generated = generate_source(_source("four.gmc"))
    ast.parse(generated)
    costs = _cost_namespace(generated)
    assert costs["cost_E0"]([2, 3, 4, 5, 6]) == 248
    assert costs["cost_E4"]([2, 3, 4, 5, 6]) == 456
    assert generated.count("def variant_E") == 5
    assert generated.count("def cost_E") == 5
    assert "VARIANTS = [variant_E0, variant_E1, variant_E2, variant_E3, variant_E4]" in generated
    assert 'LABELS = ["E0", "E1", "E2", "E3", "E4"]' in generated
    assert "q0, q1, q2, q3, q4 = q" in generated


def test_spd_module_uses_solver_flag_and_correct_cost() -> None:
    generated = generate_source(_source("good_spd.gmc"))
    costs = _cost_namespace(generated)
    assert 'POGESV(mats["A"], mats["B"], inverted_left=True)' in generated
    assert "return T1" in generated
    assert costs["cost_E0"]([4, 4, 7]) == 245


def test_generate_file_writes_utf8_python_with_final_newline(tmp_path: Path) -> None:
    output_path = tmp_path / "generated.py"
    generate_file(
        str(PROJECT_ROOT / "examples" / "simple.gmc"),
        str(output_path),
    )
    content = output_path.read_text(encoding="utf-8")
    assert content.startswith("# Generated by gmc-edu")
    assert content.endswith("\n")
    ast.parse(content)


def test_compile_cli_writes_requested_output(tmp_path: Path) -> None:
    output_path = tmp_path / "_tmp_simple.py"
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "gmc",
            "compile",
            "examples/simple.gmc",
            "-o",
            str(output_path),
        ],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0
    assert output_path.exists()
    assert "wrote _tmp_simple.py" in result.stdout
    ast.parse(output_path.read_text(encoding="utf-8"))